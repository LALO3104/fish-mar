-- =====================================================================
-- FishMar: costos de platillos y ganancias (solo dueños)
--  - insumos: lechuga, jitomate, mojarra… con su costo por kg, litro o pieza.
--    También las "preparaciones" compartidas (ej. Guarnición).
--  - receta_items: qué lleva cada producto o preparación y cuánto.
--    Las líneas "solo_para_llevar" (desechables) solo cuentan a domicilio
--    o en mesas "Para llevar".
--  - pedido_costos: el costo de cada venta, calculado al momento de la
--    venta (si después sube un insumo, las ventas pasadas no cambian).
--  - gastos: renta, sueldos, gas, luz… para la ganancia neta.
--  Todo esto solo lo pueden ver y editar los dueños (is_superadmin).
--
-- Cómo aplicarla: Supabase → SQL Editor → pegar todo → Run.
-- Si algo falla, nada se aplica (todo va en una transacción).
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. ¿Es dueño? (superadmin)
-- ---------------------------------------------------------------------
create or replace function public.es_dueno()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = auth.uid() and is_superadmin = true
  );
$$;
revoke all on function public.es_dueno() from public, anon;
grant execute on function public.es_dueno() to authenticated;

-- ---------------------------------------------------------------------
-- 2. Tablas
-- ---------------------------------------------------------------------
create table if not exists public.insumos (
  id             bigint generated by default as identity primary key,
  nombre         text not null check (char_length(btrim(nombre)) between 2 and 80),
  unidad         text not null check (unidad in ('kg', 'l', 'pieza', 'porcion')),
  costo          numeric(12,4) not null default 0 check (costo >= 0),   -- por unidad
  categoria      text not null default 'Otros',
  es_preparacion boolean not null default false,
  created_at     timestamptz not null default now()
);
create unique index if not exists insumos_nombre_unico on public.insumos (lower(btrim(nombre)));

-- receta_items y pedido_costos usan el mismo tipo de id que productos/pedidos
do $$
declare
  t_producto text;
  t_pedido   text;
begin
  select format_type(a.atttypid, a.atttypmod) into t_producto
    from pg_attribute a where a.attrelid = 'public.productos'::regclass and a.attname = 'id';
  select format_type(a.atttypid, a.atttypmod) into t_pedido
    from pg_attribute a where a.attrelid = 'public.pedidos'::regclass and a.attname = 'id';

  execute format($f$
    create table if not exists public.receta_items (
      id               bigint generated by default as identity primary key,
      producto_id      %s references public.productos(id) on delete cascade,
      preparacion_id   bigint references public.insumos(id) on delete cascade,
      insumo_id        bigint not null references public.insumos(id) on delete restrict,
      cantidad         numeric(12,4) not null check (cantidad > 0),
      solo_para_llevar boolean not null default false,
      check ((producto_id is null) <> (preparacion_id is null))
    )$f$, t_producto);

  execute format($f$
    create table if not exists public.pedido_costos (
      pedido_id     %s primary key references public.pedidos(id) on delete cascade,
      costo_insumos numeric(12,2) not null default 0,
      comision      numeric(12,2) not null default 0,
      detalle       jsonb not null default '[]'::jsonb,
      calculado_en  timestamptz not null default now()
    )$f$, t_pedido);
end $$;

create index if not exists receta_items_producto on public.receta_items (producto_id);
create index if not exists receta_items_preparacion on public.receta_items (preparacion_id);

create table if not exists public.gastos (
  id         bigint generated by default as identity primary key,
  fecha      date not null default ((now() at time zone 'America/Mexico_City')::date),
  categoria  text not null,
  concepto   text,
  monto      numeric(12,2) not null check (monto > 0),
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);
create index if not exists gastos_fecha on public.gastos (fecha);

-- ---------------------------------------------------------------------
-- 3. Permisos: solo dueños
-- ---------------------------------------------------------------------
alter table public.insumos       enable row level security;
alter table public.receta_items  enable row level security;
alter table public.pedido_costos enable row level security;
alter table public.gastos        enable row level security;

drop policy if exists insumos_duenos on public.insumos;
create policy insumos_duenos on public.insumos
  for all to authenticated using (public.es_dueno()) with check (public.es_dueno());

drop policy if exists receta_items_duenos on public.receta_items;
create policy receta_items_duenos on public.receta_items
  for all to authenticated using (public.es_dueno()) with check (public.es_dueno());

drop policy if exists pedido_costos_duenos on public.pedido_costos;
create policy pedido_costos_duenos on public.pedido_costos
  for select to authenticated using (public.es_dueno());

drop policy if exists gastos_duenos on public.gastos;
create policy gastos_duenos on public.gastos
  for all to authenticated using (public.es_dueno()) with check (public.es_dueno());

-- ---------------------------------------------------------------------
-- 4. Cálculo de costos
-- ---------------------------------------------------------------------
-- Costo por unidad de un insumo (si es preparación, la suma de su receta)
create or replace function public.costo_insumo(p_insumo_id bigint)
returns numeric
language sql stable security definer
set search_path = public
as $$
  select case
    when i.es_preparacion then coalesce((
      select sum(r.cantidad * c.costo)
        from public.receta_items r
        join public.insumos c on c.id = r.insumo_id
       where r.preparacion_id = i.id), 0)
    else i.costo
  end
  from public.insumos i
  where i.id = p_insumo_id;
$$;

-- Costo de 1 unidad de un producto (1 pieza, o 1 kg si se vende por kilo)
create or replace function public.costo_unitario_producto(p_producto_id bigint, p_para_llevar boolean)
returns numeric
language sql stable security definer
set search_path = public
as $$
  select coalesce(sum(r.cantidad * public.costo_insumo(r.insumo_id)), 0)
    from public.receta_items r
   where r.producto_id = p_producto_id
     and (not r.solo_para_llevar or p_para_llevar);
$$;

-- Calcula y guarda el costo de una venta con los costos de este momento
create or replace function public.recalcular_costo_pedido(p_pedido_id bigint)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  v_row     jsonb;
  v_llevar  boolean;
  v_item    jsonb;
  v_pid     bigint;
  v_qty     numeric;
  v_cu      numeric;
  v_total   numeric := 0;
  v_detalle jsonb := '[]'::jsonb;
begin
  select to_jsonb(p) into v_row from public.pedidos p where p.id = p_pedido_id;
  if v_row is null then
    return;
  end if;

  -- Desechables: domicilio o mesas "Para llevar"
  v_llevar := coalesce(v_row->>'tipo_pedido', '') <> 'local'
              or coalesce(v_row->>'mesa', '') ilike 'para llevar%';

  for v_item in select * from jsonb_array_elements(
      case when jsonb_typeof(v_row->'items') = 'array' then v_row->'items' else '[]'::jsonb end) loop
    v_pid := case when (v_item->>'id') ~ '^[0-9]+$' then (v_item->>'id')::bigint end;
    v_qty := coalesce(nullif(v_item->>'qty', '')::numeric, 0);
    v_cu  := case when v_pid is null then 0 else public.costo_unitario_producto(v_pid, v_llevar) end;
    v_total := v_total + v_cu * v_qty;
    v_detalle := v_detalle || jsonb_build_object(
      'id', v_pid,
      'nombre', v_item->>'nombre',
      'qty', v_qty,
      'precio', coalesce(nullif(v_item->>'precio', '')::numeric, 0),
      'costo_unitario', round(v_cu, 4)
    );
  end loop;

  insert into public.pedido_costos (pedido_id, costo_insumos, comision, detalle, calculado_en)
  values (
    p_pedido_id,
    round(v_total, 2),
    coalesce(nullif(v_row->>'comision_tarjeta', '')::numeric, 0),
    v_detalle,
    now()
  )
  on conflict (pedido_id) do update
    set costo_insumos = excluded.costo_insumos,
        comision      = excluded.comision,
        detalle       = excluded.detalle,
        calculado_en  = excluded.calculado_en;
end;
$$;
revoke all on function public.recalcular_costo_pedido(bigint) from public, anon, authenticated;

-- Se recalcula sola cada vez que cambian los productos de una venta
create or replace function public.trg_calcular_costo_pedido()
returns trigger
language plpgsql security definer
set search_path = public
as $$
begin
  if tg_op = 'UPDATE'
     and (to_jsonb(new)->'items') is not distinct from (to_jsonb(old)->'items')
     and (to_jsonb(new)->'comision_tarjeta') is not distinct from (to_jsonb(old)->'comision_tarjeta') then
    return null;
  end if;
  perform public.recalcular_costo_pedido(new.id);
  return null;
end;
$$;

drop trigger if exists calcular_costo_pedido on public.pedidos;
create trigger calcular_costo_pedido
  after insert or update on public.pedidos
  for each row execute function public.trg_calcular_costo_pedido();

-- ---------------------------------------------------------------------
-- 5. Funciones para la pantalla de los dueños
-- ---------------------------------------------------------------------
-- Guardar la receta completa de un producto o de una preparación
create or replace function public.guardar_receta(p_producto_id bigint, p_preparacion_id bigint, p_items jsonb)
returns void
language plpgsql security definer
set search_path = public
as $$
begin
  if not public.es_dueno() then
    raise exception 'Solo los dueños pueden editar recetas.';
  end if;
  if (p_producto_id is null) = (p_preparacion_id is null) then
    raise exception 'Receta inválida.';
  end if;
  if p_preparacion_id is not null
     and not exists (select 1 from public.insumos where id = p_preparacion_id and es_preparacion) then
    raise exception 'La preparación no existe.';
  end if;
  if p_preparacion_id is not null and exists (
      select 1 from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) e
        join public.insumos i on i.id = (e->>'insumo_id')::bigint
       where i.es_preparacion) then
    raise exception 'Una preparación no puede llevar otra preparación.';
  end if;

  delete from public.receta_items
   where (p_producto_id is not null and producto_id = p_producto_id)
      or (p_preparacion_id is not null and preparacion_id = p_preparacion_id);

  insert into public.receta_items (producto_id, preparacion_id, insumo_id, cantidad, solo_para_llevar)
  select p_producto_id, p_preparacion_id,
         (e->>'insumo_id')::bigint,
         (e->>'cantidad')::numeric,
         coalesce((e->>'solo_para_llevar')::boolean, false)
    from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) e;
end;
$$;
revoke all on function public.guardar_receta(bigint, bigint, jsonb) from public, anon;
grant execute on function public.guardar_receta(bigint, bigint, jsonb) to authenticated;

-- Volver a calcular el costo de ventas pasadas con los costos actuales
create or replace function public.recalcular_costos(p_desde date, p_hasta date)
returns integer
language plpgsql security definer
set search_path = public
as $$
declare
  v_desde timestamptz := (p_desde::timestamp at time zone 'America/Mexico_City');
  v_hasta timestamptz := ((p_hasta + 1)::timestamp at time zone 'America/Mexico_City');
  v_id    bigint;
  v_n     integer := 0;
begin
  if not public.es_dueno() then
    raise exception 'Solo los dueños pueden recalcular costos.';
  end if;
  for v_id in
    select p.id from public.pedidos p
     where (p.created_at::timestamptz >= v_desde and p.created_at::timestamptz < v_hasta)
        or (nullif(to_jsonb(p)->>'fecha_cierre', '')::timestamptz >= v_desde
            and nullif(to_jsonb(p)->>'fecha_cierre', '')::timestamptz < v_hasta)
  loop
    perform public.recalcular_costo_pedido(v_id);
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;
revoke all on function public.recalcular_costos(date, date) from public, anon;
grant execute on function public.recalcular_costos(date, date) to authenticated;

-- Reporte de ganancias de un período (fechas en hora de México)
create or replace function public.reporte_ganancias(p_desde date, p_hasta date)
returns json
language plpgsql stable security definer
set search_path = public
as $$
declare
  v_desde timestamptz := (p_desde::timestamp at time zone 'America/Mexico_City');
  v_hasta timestamptz := ((p_hasta + 1)::timestamp at time zone 'America/Mexico_City');
  r json;
begin
  if not public.es_dueno() then
    raise exception 'Solo los dueños pueden ver las ganancias.';
  end if;

  with base as (
    select p.id,
           to_jsonb(p) as j,
           nullif(to_jsonb(p)->>'total', '')::numeric as total
      from public.pedidos p
  ),
  ventas as (
    -- Domicilio entregado (por día del pedido) + mesas cobradas (por día de cierre)
    select b.id,
           coalesce(b.total, 0) as total,
           case when b.j->>'tipo_pedido' = 'local' then 'restaurante' else 'domicilio' end as canal,
           coalesce(c.costo_insumos, 0) as costo,
           coalesce(c.comision, 0) as comision,
           coalesce(c.detalle, '[]'::jsonb) as detalle,
           c.pedido_id is null as sin_costo
      from base b
      left join public.pedido_costos c on c.pedido_id = b.id
     where (coalesce(b.j->>'tipo_pedido', '') <> 'local'
            and b.j->>'estado' = 'Entregado'
            and (b.j->>'created_at')::timestamptz >= v_desde
            and (b.j->>'created_at')::timestamptz <  v_hasta)
        or (b.j->>'tipo_pedido' = 'local'
            and b.j->>'estado_local' = 'cerrado'
            and nullif(b.j->>'fecha_cierre', '')::timestamptz >= v_desde
            and nullif(b.j->>'fecha_cierre', '')::timestamptz <  v_hasta)
  ),
  por_producto as (
    select d->>'nombre' as nombre,
           sum((d->>'qty')::numeric) as cantidad,
           round(sum((d->>'qty')::numeric * (d->>'precio')::numeric), 2) as venta,
           round(sum((d->>'qty')::numeric * (d->>'costo_unitario')::numeric), 2) as costo,
           bool_or((d->>'costo_unitario')::numeric = 0) as sin_receta
      from ventas v, jsonb_array_elements(v.detalle) d
     group by d->>'nombre'
  ),
  gastos_periodo as (
    select categoria, sum(monto) as monto
      from public.gastos
     where fecha between p_desde and p_hasta
     group by categoria
  )
  select json_build_object(
    'ventas',        coalesce((select sum(total) from ventas), 0),
    'costo_insumos', coalesce((select sum(costo) from ventas), 0),
    'comisiones',    coalesce((select sum(comision) from ventas), 0),
    'gastos',        coalesce((select sum(monto) from gastos_periodo), 0),
    'pedidos',       (select count(*) from ventas),
    'pedidos_sin_costo', (select count(*) from ventas where sin_costo),
    'por_canal', coalesce((
        select json_agg(json_build_object('canal', canal, 'pedidos', n, 'ventas', v, 'costo', c))
          from (select canal, count(*) n, sum(total) v, sum(costo) c from ventas group by canal) x), '[]'),
    'gastos_por_categoria', coalesce((
        select json_agg(json_build_object('categoria', categoria, 'monto', monto) order by monto desc)
          from gastos_periodo), '[]'),
    'productos', coalesce((
        select json_agg(json_build_object(
                 'nombre', nombre, 'cantidad', cantidad, 'venta', venta,
                 'costo', costo, 'ganancia', venta - costo, 'sin_receta', sin_receta)
               order by venta - costo desc)
          from por_producto), '[]')
  ) into r;

  return r;
end;
$$;
revoke all on function public.reporte_ganancias(date, date) from public, anon;
grant execute on function public.reporte_ganancias(date, date) to authenticated;

commit;
